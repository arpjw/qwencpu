"""Text fidelity of a dynamic byte-CPU Qwen3.5-9B merge against base 9B.

This is a small, fixed, single-position comparison with optional eight-token
greedy continuations. It also probes text after a generated byte-CPU trace.
Run on a CUDA machine with both checkpoints; results are written as JSON.
"""

from __future__ import annotations

import argparse
import gc
import hashlib
import json
import time
from pathlib import Path

import torch

from gdn_cpu.qwen8 import state_token
from gdn_cpu.reference import CPUState, step


PROMPTS = (
    "Hello! Tell me one interesting fact about the Moon.",
    "Summarize this in one sentence: A small team repaired a bridge overnight so buses could run at dawn.",
    "Write a Python function that reverses a list without changing the original.",
    "What is the difference between a mutex and a semaphore?",
    "Explain why ice floats on liquid water.",
    "Continue this JSON object with one field: {\"status\": \"ok\"",
    "Make a short numbered checklist for packing a weekend bag.",
    "Translate 'Good morning, how are you?' into Spanish.",
    "The café opened in 東京. Describe the scene in English.",
    "Complete the sentence: In a proof by induction, the base case",
    "A customer says the app froze after saving. Give a concise support reply.",
    "List two possible causes of a slow database query.",
)
HANDOFF_PROMPTS = (PROMPTS[0], PROMPTS[3])
DEFAULT_CPU_PROGRAM = "10ff200230001000500e400050102001ff"


def _ids(tokenizer, text: str) -> list[int]:
    messages = [{"role": "user", "content": text}]
    encoded = tokenizer.apply_chat_template(messages, add_generation_prompt=True,
                                             enable_thinking=False, tokenize=True)
    if not isinstance(encoded, list):
        encoded = encoded["input_ids"]
    return [int(token) for token in encoded]


def _metrics(base: torch.Tensor, other: torch.Tensor) -> dict:
    base, other = base.float(), other.float()
    bp, op = torch.log_softmax(base, -1), torch.log_softmax(other, -1)
    return {"kl_base_to_other": float((bp.exp() * (bp - op)).sum()),
            "max_abs_logit_difference": float((base - other).abs().max()),
            "same_top1": int(base.argmax()) == int(other.argmax()),
            "base_top1": int(base.argmax()), "other_top1": int(other.argmax())}


@torch.no_grad()
def _next_logits(model, ids: list[int], text_vocab: int, device: str) -> torch.Tensor:
    sequence = torch.tensor([ids], device=device)
    return model(input_ids=sequence).logits[0, -1, :text_vocab].float().cpu()


def _compressed_positions(text_tokens: int, cpu_tokens: int) -> list[int]:
    """Give CPU tokens the preceding text position, preserving text positions."""
    prefix = text_tokens - 1
    if prefix < 1:
        raise ValueError("handoff text prompt needs a nonempty prefix")
    return [*range(prefix), *([prefix - 1] * cpu_tokens), prefix]


@torch.no_grad()
def _greedy(model, ids: list[int], new_tokens: int, device: str,
            pad_token_id: int) -> list[int]:
    result = model.generate(torch.tensor([ids], device=device), max_new_tokens=new_tokens,
                            do_sample=False, pad_token_id=pad_token_id)
    return result[0, len(ids):].tolist()


def _expected_cpu_tokens(program: bytes, offset: int) -> list[int]:
    state = CPUState()
    out = []
    for _ in range(256):
        state = step(state, program)
        out.extend((offset + 131072, offset + state_token(state)))
        if state.halted:
            return out
    raise ValueError("handoff CPU program did not halt within 256 steps")


def run(base_dir: Path, merged_dir: Path, *, new_tokens: int = 8,
        cpu_program: bytes = bytes.fromhex(DEFAULT_CPU_PROGRAM),
        device: str | None = None) -> dict:
    from transformers import AutoModelForImageTextToText, AutoTokenizer, Qwen3_5ForCausalLM
    import transformers

    device = device or ("cuda" if torch.cuda.is_available() else "cpu")
    if device == "cuda" and not torch.cuda.is_available():
        raise RuntimeError("CUDA was requested but is unavailable")
    started = time.monotonic()
    meta = json.loads((merged_dir / "byte9b.json").read_text(encoding="utf-8"))
    if meta["mode"] != "dynamic":
        raise ValueError("this text check requires a dynamic byte checkpoint")
    if len(cpu_program) > meta["rom_size"]:
        raise ValueError("handoff CPU program exceeds checkpoint ROM capacity")
    base_tok = AutoTokenizer.from_pretrained(base_dir)
    merged_tok = AutoTokenizer.from_pretrained(merged_dir)
    text_vocab = meta["chip_token_offset"]
    base_ids = [_ids(base_tok, prompt) for prompt in PROMPTS]
    merged_ids = [_ids(merged_tok, prompt) for prompt in PROMPTS]
    tokenizer_same = [left == right for left, right in zip(base_ids, merged_ids, strict=True)]
    if not all(tokenizer_same):
        raise ValueError("base and merged tokenizer disagree on a fixed prompt")
    pad = base_tok.pad_token_id or base_tok.eos_token_id or 248044

    base_config = json.loads((base_dir / "config.json").read_text(encoding="utf-8"))
    base_class = (Qwen3_5ForCausalLM if base_config.get("model_type") == "qwen3_5_text"
                  else AutoModelForImageTextToText)
    base_model = base_class.from_pretrained(base_dir,
                                            dtype=torch.bfloat16).to(device).eval()
    base_rows = []
    base_cont = []
    for ids in base_ids:
        base_rows.append(_next_logits(base_model, ids, text_vocab, device))
        base_cont.append(_greedy(base_model, ids, new_tokens, device, pad))
    del base_model
    gc.collect()
    if device == "cuda":
        torch.cuda.empty_cache()

    merged = Qwen3_5ForCausalLM.from_pretrained(
        merged_dir, dtype=torch.bfloat16).to(device).eval()
    records = []
    for prompt, ids, base_row, base_gen in zip(
            PROMPTS, merged_ids, base_rows, base_cont, strict=True):
        merged_row = _next_logits(merged, ids, text_vocab, device)
        merged_gen = _greedy(merged, ids, new_tokens, device, pad)
        records.append({"prompt": prompt, "prompt_tokens": len(ids),
                        "tokenizer_ids_same": True,
                        "next_token": _metrics(base_row, merged_row),
                        "greedy_identical": base_gen == merged_gen,
                        "base_greedy_ids": base_gen,
                        "merged_greedy_ids": merged_gen,
                        "cpu_ids_in_merged_greedy": sum(t >= text_vocab for t in merged_gen)})

    from gdn_cpu.qwen8_dynamic import PAD, program_tokens

    offset = text_vocab
    cpu_prefix = [offset + PAD,
                  *(offset + token for token in program_tokens(
                      cpu_program, rom_size=meta["rom_size"])),
                  offset + state_token(CPUState())]
    expected = _expected_cpu_tokens(cpu_program, offset)
    with torch.no_grad():
        generated = merged.generate(
            torch.tensor([cpu_prefix], device=device), max_new_tokens=len(expected),
            do_sample=False, pad_token_id=offset + PAD, eos_token_id=None,
            cache_implementation="dynamic")[0, len(cpu_prefix):].tolist()
    handoff = []
    for prompt in HANDOFF_PROMPTS:
        ids = merged_ids[PROMPTS.index(prompt)]
        with_cpu = [*ids[:-1], *cpu_prefix, *generated, ids[-1]]
        positions = _compressed_positions(len(ids), len(cpu_prefix) + len(generated))
        plain_row = _next_logits(merged, ids, text_vocab, device)
        after_row = _next_logits(merged, with_cpu, text_vocab, device)
        # This is a teacher-forced trace check under compressed positions.
        # The model-generated CPU trace itself was produced above with stock
        # positions, so this does not claim free-running compressed decoding.
        with torch.no_grad():
            sequence = torch.tensor([with_cpu], device=device)
            pos_tensor = torch.tensor([positions], device=device)
            logits = merged(input_ids=sequence, position_ids=pos_tensor).logits[0]
            compressed_row = logits[-1, :text_vocab].float().cpu()
            state_index = len(ids) - 1 + len(cpu_prefix) - 1
            predicted = logits[state_index:state_index + len(generated)].argmax(-1).tolist()
        handoff.append({"prompt": prompt, "text_tokens": len(ids),
                        "cpu_context_tokens": len(cpu_prefix) + len(generated),
                        "plain_vs_after_cpu": _metrics(plain_row, after_row),
                        "plain_vs_compressed": _metrics(plain_row, compressed_row),
                        "after_cpu_vs_compressed": _metrics(after_row, compressed_row),
                        "compressed_cpu_teacher_forced_next_matches": sum(
                            a == b for a, b in zip(predicted, generated, strict=True)),
                        "compressed_cpu_teacher_forced_next_exact": predicted == generated,
                        "compressed_cpu_predicted_tokens": predicted})

    return {"schema": 1, "base": str(base_dir), "merged": str(merged_dir),
            "model_layout": meta["layout"], "rom_size": meta["rom_size"],
            "device": device, "torch": torch.__version__,
            "transformers": transformers.__version__,
            "prompt_sha256": hashlib.sha256(json.dumps(PROMPTS).encode()).hexdigest(),
            "new_tokens": new_tokens, "prompt_count": len(PROMPTS),
            "tokenizer_identical": tokenizer_same,
            "next_token_top1_same": sum(r["next_token"]["same_top1"] for r in records),
            "greedy_identical": sum(r["greedy_identical"] for r in records),
            "next_token_kl_mean": sum(r["next_token"]["kl_base_to_other"]
                                      for r in records) / len(records),
            "records": records,
            "handoff_cpu_program": cpu_program.hex(),
            "handoff_cpu_expected_tokens": expected,
            "handoff_cpu_generated_tokens": generated,
            "handoff_cpu_exact": generated == expected,
            "compressed_position_rule": "CPU tokens reuse the preceding text position; "
                                        "the next text token retains its original position",
            "handoff": handoff,
            "handoff_stock_top1_same": sum(
                row["plain_vs_after_cpu"]["same_top1"] for row in handoff),
            "handoff_compressed_top1_same": sum(
                row["plain_vs_compressed"]["same_top1"] for row in handoff),
            "compressed_cpu_teacher_forced_all_exact": all(
                row["compressed_cpu_teacher_forced_next_exact"] for row in handoff),
            "seconds": round(time.monotonic() - started, 3)}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("base", type=Path)
    parser.add_argument("merged", type=Path)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--new-tokens", type=int, default=8)
    parser.add_argument("--cpu-program", default=DEFAULT_CPU_PROGRAM)
    parser.add_argument("--device", choices=("cuda", "cpu", "mps"),
                        default="cuda" if torch.cuda.is_available() else "cpu")
    args = parser.parse_args()
    if args.new_tokens < 1:
        parser.error("--new-tokens must be positive")
    report = run(args.base, args.merged, new_tokens=args.new_tokens,
                 cpu_program=bytes.fromhex(args.cpu_program), device=args.device)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n",
                        encoding="utf-8")
    print(json.dumps({key: report[key] for key in
                      ("prompt_count", "next_token_top1_same", "greedy_identical",
                       "next_token_kl_mean", "handoff_cpu_exact",
                       "handoff_stock_top1_same", "handoff_compressed_top1_same",
                       "compressed_cpu_teacher_forced_all_exact", "seconds")}), flush=True)


if __name__ == "__main__":
    main()
